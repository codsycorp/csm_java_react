// ── Normalize dict keys to NFC for consistent lookup ─────────────────────────
function normDict(d) {
  const out = {};
  for (const [k, v] of Object.entries(d)) out[k.normalize('NFC')] = v;
  return out;
}
const MENU_EN_N = normDict(MENU_EN);
const MENU_ZH_N = normDict(MENU_ZH);
const FIELD_EN_N = { ...normDict(FIELD_EN),
  'Số điện thoại': 'Phone No.',
  'Chi (tiền măt)': 'Cash Payment',
  'Tổng khách': 'Total Guests',
};
const FIELD_ZH_N = { ...normDict(FIELD_ZH),
  'Số điện thoại': '电话号码',
  'Chi (tiền măt)': '现金支出',
  'Tổng khách': '客人总数',
};

const nfc = s => (s || '').normalize('NFC');

// ── Patch function ─────────────────────────────────────────────────────────────

function patchFile(filePath) {
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
  let menuPatched = 0, fieldPatched = 0, missing = new Set();

  data.menus_flat.forEach(m => {
    if (!m.label_en && m.label) {
      const en = MENU_EN_N[nfc(m.label)];
      if (en) { m.label_en = en; menuPatched++; } else missing.add('MENU:' + m.label);
    }
    if (!m.label_zh && m.label) {
      const zh = MENU_ZH_N[nfc(m.label)];
      if (zh) { m.label_zh = zh; } else missing.add('MENU:' + m.label);
    }
    const fields = Array.isArray(m.table) ? m.table : [];
    fields.forEach(f => {
      const vi = nfc(f.f_header_vi || f.f_header || '');
      if (vi) {
        if (!f.f_header_en) {
          const en = FIELD_EN_N[vi];
          if (en) { f.f_header_en = en; fieldPatched++; } else missing.add('FIELD:' + vi);
        }
        if (!f.f_header_zh) {
          const zh = FIELD_ZH_N[vi];
          if (zh) { f.f_header_zh = zh; } else missing.add('FIELD:' + vi);
        }
      }
    });
  });

  // Also patch tree menus (label_en/label_zh)
  function patchTree(items) {
    if (!items) return;
    items.forEach(m => {
      const k = nfc(m.label);
      if (!m.label_en && m.label && MENU_EN_N[k]) m.label_en = MENU_EN_N[k];
      if (!m.label_zh && m.label && MENU_ZH_N[k]) m.label_zh = MENU_ZH_N[k];
      patchTree(m.children);
      patchTree(m.nodes);
    });
  }
  patchTree(data.menus);

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
  console.log(`✓ ${path.basename(filePath)}: ${menuPatched} menu labels, ${fieldPatched} field headers patched`);
  if (missing.size > 0) {
    console.log('  Missing translations:');
    [...missing].sort().forEach(k => console.log('    ' + k));
  }
}

